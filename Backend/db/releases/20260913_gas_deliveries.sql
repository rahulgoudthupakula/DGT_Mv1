-- Production Gas Delivery release authorized on 2026-09-13.
-- BOL records are independent of invoices because they contain no prices.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
DO $$ BEGIN IF current_database()<>'dgt' THEN RAISE EXCEPTION 'Production dgt required'; END IF; END $$;
ALTER TABLE fuel_tanks ADD CONSTRAINT gas_delivery_tank_store_key UNIQUE(tank_id,dgt_id);
CREATE TABLE fuel_deliveries (
 delivery_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dgt_id varchar(50) NOT NULL REFERENCES stores(dgt_id),
 vendor_id bigint NOT NULL,
 client_request_id uuid NOT NULL,
 request_hash varchar(64) NOT NULL,
 UNIQUE(dgt_id,client_request_id),
 bol_number varchar(100) NOT NULL CHECK(length(trim(bol_number))>0),
 folio varchar(100),
 load_date date NOT NULL,
 load_time time,
 terminal varchar(250),
 customer_account varchar(250),
 destination varchar(500),
 carrier_name varchar(200),
 driver_name varchar(200),
 tractor_number varchar(100),
 trailer_number varchar(100),
 notes text,
 status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','RECEIVED')),
 created_by bigint NOT NULL REFERENCES users(user_id),
 received_by bigint REFERENCES users(user_id),
 received_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(delivery_id,dgt_id),
 FOREIGN KEY(vendor_id,dgt_id) REFERENCES vendors(vendor_id,dgt_id),
 CHECK((status='DRAFT' AND received_by IS NULL AND received_at IS NULL) OR
       (status='RECEIVED' AND received_by IS NOT NULL AND received_at IS NOT NULL))
);
CREATE UNIQUE INDEX fuel_delivery_vendor_bol_key ON fuel_deliveries(dgt_id,vendor_id,lower(trim(bol_number)));
CREATE TABLE fuel_delivery_lines (
 delivery_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 delivery_id bigint NOT NULL,
 dgt_id varchar(50) NOT NULL,
 line_number integer NOT NULL CHECK(line_number>0),
 tank_id bigint NOT NULL,
 fuel_grade_id bigint NOT NULL REFERENCES fuel_grades(fuel_grade_id),
 product_code varchar(100),
 description varchar(300),
 octane numeric(5,2) CHECK(octane>=0),
 gross_gallons numeric(14,3) NOT NULL CHECK(gross_gallons>0),
 net_gallons numeric(14,3) NOT NULL CHECK(net_gallons>0),
 temperature numeric(7,3),
 gravity numeric(7,3),
 meter varchar(100),
 compartment varchar(100),
 UNIQUE(delivery_id,line_number),
 UNIQUE(delivery_line_id,dgt_id,tank_id,fuel_grade_id),
 FOREIGN KEY(delivery_id,dgt_id) REFERENCES fuel_deliveries(delivery_id,dgt_id),
 FOREIGN KEY(tank_id,dgt_id) REFERENCES fuel_tanks(tank_id,dgt_id)
);
-- Retain the existing movement ledger. Product movement requirements stay intact.
ALTER TABLE inventory_movements
 ALTER COLUMN product_id DROP NOT NULL,
 ALTER COLUMN unit_cost DROP NOT NULL,
 ADD COLUMN tank_id bigint,
 ADD COLUMN fuel_grade_id bigint REFERENCES fuel_grades(fuel_grade_id),
 ADD COLUMN fuel_delivery_line_id bigint,
 ADD COLUMN net_gallons numeric(14,3),
 ADD CONSTRAINT fuel_movement_tank_store_fk FOREIGN KEY(tank_id,dgt_id) REFERENCES fuel_tanks(tank_id,dgt_id),
 ADD CONSTRAINT fuel_movement_delivery_line_fk FOREIGN KEY(fuel_delivery_line_id,dgt_id,tank_id,fuel_grade_id)
  REFERENCES fuel_delivery_lines(delivery_line_id,dgt_id,tank_id,fuel_grade_id),
 ADD CONSTRAINT inventory_movement_subject_check CHECK (
  (product_id IS NOT NULL AND unit_cost IS NOT NULL AND tank_id IS NULL AND fuel_grade_id IS NULL AND fuel_delivery_line_id IS NULL AND net_gallons IS NULL)
  OR (product_id IS NULL AND tank_id IS NOT NULL AND fuel_grade_id IS NOT NULL AND fuel_delivery_line_id IS NOT NULL
      AND movement_type='FUEL_DELIVERY' AND qty_changed>0 AND net_gallons IS NOT NULL AND net_gallons>0)
 ),
 ADD CONSTRAINT fuel_delivery_post_once UNIQUE(fuel_delivery_line_id);
-- Fuel delivery movement qty_changed is gross gallons; net_gallons retained separately.
-- Unpriced fuel movement cost remains NULL until invoice reconciliation is implemented.
-- No changes to grocery product balances and no synthetic physical tank readings.
DO $$
DECLARE existing_rule text;
BEGIN
 SELECT pg_get_expr(conbin,conrelid) INTO STRICT existing_rule FROM pg_constraint
 WHERE conrelid='store_role_permissions'::regclass AND conname='store_role_permissions_permission_code_check';
 ALTER TABLE store_role_permissions DROP CONSTRAINT store_role_permissions_permission_code_check;
 EXECUTE format('ALTER TABLE store_role_permissions ADD CONSTRAINT store_role_permissions_permission_code_check CHECK ((%s) OR permission_code IN (''GAS_VIEW_DELIVERIES'',''GAS_RECORD_DELIVERY'',''GAS_RECEIVE_DELIVERY''))',existing_rule);
END $$;
COMMIT;
