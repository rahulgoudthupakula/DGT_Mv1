 EXECUTE format('ALTER TABLE store_role_permissions ADD CONSTRAINT store_role_permissions_permission_code_check CHECK ((%s) OR permission_code IN (''GAS_VIEW_ADJUSTMENTS'',''GAS_RECORD_ADJUSTMENT'',''GAS_APPROVE_ADJUSTMENT''))',rule);
