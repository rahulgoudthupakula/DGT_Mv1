BEGIN;
DO $$ BEGIN IF current_database()<>'dgt' THEN RAISE EXCEPTION 'Production dgt required'; END IF; END $$;
CREATE TABLE fuel_adjustments (
 adjustment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dgt_id varchar(50) NOT NULL REFERENCES stores(dgt_id),
 client_request_id uuid NOT NULL,
 request_hash varchar(64) NOT NULL,
 adjustment_date date NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PENDING','POSTED','REJECTED')),
 notes text,
 created_by bigint NOT NULL REFERENCES users(user_id),
 reviewed_by bigint REFERENCES users(user_id),
 reviewed_at timestamptz,
 rejection_reason text,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(dgt_id,client_request_id), UNIQUE(adjustment_id,dgt_id),
 CHECK((status IN ('DRAFT','PENDING') AND reviewed_by IS NULL AND reviewed_at IS NULL)
 OR (status IN ('POSTED','REJECTED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
 CHECK(status<>'REJECTED' OR length(trim(rejection_reason))>0)
);
CREATE TABLE fuel_adjustment_lines (
 adjustment_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 adjustment_id bigint NOT NULL,
 dgt_id varchar(50) NOT NULL,
 tank_id bigint NOT NULL,
 fuel_grade_id bigint NOT NULL REFERENCES fuel_grades(fuel_grade_id),
 system_gallons numeric(12,3) NOT NULL CHECK(system_gallons>=0),
 actual_gallons numeric(12,3) NOT NULL CHECK(actual_gallons>=0),
 difference_gallons numeric(12,3) GENERATED ALWAYS AS (actual_gallons-system_gallons) STORED,
 baseline_reading_id bigint NOT NULL REFERENCES fuel_tank_readings(tank_reading_id),
 baseline_movement_id bigint,
 reason varchar(30) NOT NULL CHECK(reason IN ('meter_variance','evaporation','leak','theft','calibration','other')),
 UNIQUE(adjustment_id,tank_id),
 UNIQUE(adjustment_line_id,dgt_id,tank_id,fuel_grade_id),
 FOREIGN KEY(adjustment_id,dgt_id) REFERENCES fuel_adjustments(adjustment_id,dgt_id),
 FOREIGN KEY(tank_id,dgt_id) REFERENCES fuel_tanks(tank_id,dgt_id)
);
ALTER TABLE inventory_movements ADD COLUMN fuel_adjustment_line_id bigint,
 ADD CONSTRAINT fuel_movement_adjustment_line_fk FOREIGN KEY(fuel_adjustment_line_id,dgt_id,tank_id,fuel_grade_id)
 REFERENCES fuel_adjustment_lines(adjustment_line_id,dgt_id,tank_id,fuel_grade_id),
 ADD CONSTRAINT fuel_adjustment_post_once UNIQUE(fuel_adjustment_line_id);
ALTER TABLE inventory_movements DROP CONSTRAINT inventory_movement_subject_check;
ALTER TABLE inventory_movements ADD CONSTRAINT inventory_movement_subject_check CHECK (
 (product_id IS NOT NULL AND unit_cost IS NOT NULL AND tank_id IS NULL AND fuel_grade_id IS NULL AND fuel_delivery_line_id IS NULL AND fuel_adjustment_line_id IS NULL AND net_gallons IS NULL)
 OR (product_id IS NULL AND tank_id IS NOT NULL AND fuel_grade_id IS NOT NULL AND fuel_delivery_line_id IS NOT NULL AND fuel_adjustment_line_id IS NULL AND movement_type='FUEL_DELIVERY' AND qty_changed>0 AND net_gallons IS NOT NULL AND net_gallons>0)
 OR (product_id IS NULL AND tank_id IS NOT NULL AND fuel_grade_id IS NOT NULL AND fuel_delivery_line_id IS NULL AND fuel_adjustment_line_id IS NOT NULL AND movement_type='FUEL_ADJUSTMENT' AND qty_changed<>0 AND unit_cost IS NULL AND net_gallons IS NULL)
);
