CREATE FUNCTION initialize_store_departments(store_code varchar) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO store_departments(dgt_id,department_id,store_department_name,source_type)
 SELECT store_code,department_id,department_name,'DEFAULT' FROM departments
 ON CONFLICT(dgt_id,department_id) DO NOTHING;
 INSERT INTO store_sub_departments(dgt_id,store_department_id,store_sub_department_name,source_type)
 SELECT store_code,sd.store_department_id,sub.sub_department_name,'DEFAULT'
 FROM store_departments sd JOIN sub_departments sub ON sub.department_id=sd.department_id
 WHERE sd.dgt_id=store_code AND NOT EXISTS (
 SELECT 1 FROM store_sub_departments existing WHERE existing.store_department_id=sd.store_department_id
 AND lower(trim(existing.store_sub_department_name))=lower(trim(sub.sub_department_name)))
 ON CONFLICT(store_department_id,store_sub_department_name) DO NOTHING;
END $$;
-- Backfill missing records only: existing names, activation, tax, margin and product links survive.
SELECT initialize_store_departments(dgt_id) FROM stores;
CREATE FUNCTION initialize_new_store_departments() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM initialize_store_departments(NEW.dgt_id);
 RETURN NEW;
END $$;
CREATE TRIGGER initialize_store_department_catalog AFTER INSERT ON stores
FOR EACH ROW EXECUTE FUNCTION initialize_new_store_departments();
